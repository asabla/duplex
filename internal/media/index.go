// InspectCombined checks finite MP4 sample tables and supported audio/video
// descriptions without fetching the full object. Decode acceptance is a release
// test; container checks are repeated for every selected source revision.
func InspectCombined(ctx context.Context, source Representation) (Details, error) {
	info := Details{Container: "mp4"}
	movie, err := readMoov(ctx, source)
	if err != nil {
		return info, err
	}
	if movie.Mvex != nil {
		return info, ErrUnsupported
	}
	video, audio := false, false
	for _, track := range movie.Traks {
		kind, err := combinedTrackKind(track)
		if err != nil {
			return info, err
		}
		switch track.Mdia.Hdlr.HandlerType {
		case "vide":
			if video || !videoCodec(kind) {
				return info, ErrUnsupported
			}
			video = true
			if err = combinedVideoDetails(track, &info); err != nil {
				return info, err
			}
		case "soun":
			if audio || !audioCodec(kind) {
				return info, ErrUnsupported
			}
			audio = true
			info.AudioCodec = kind
		}
	}
	if !video || !audio || info.Height <= 0 || info.Width <= 0 || info.DurationSeconds <= 0 || info.DurationSeconds > 31*86400 {
		return info, ErrUnsupported
	}
	return info, nil
}

func combinedTrackKind(track *mp4.TrakBox) (string, error) {
	if track.Mdia == nil || track.Mdia.Hdlr == nil || track.Mdia.Minf == nil || track.Mdia.Minf.Stbl == nil {
		return "", ErrUnsupported
	}
	table := track.Mdia.Minf.Stbl
	if table.Stsd == nil || len(table.Stsd.Children) != 1 || table.Stsz == nil || table.Stsz.GetNrSamples() == 0 || table.Stts == nil {
		return "", ErrUnsupported
	}
	return table.Stsd.Children[0].Type(), nil
}

func combinedVideoDetails(track *mp4.TrakBox, info *Details) error {
	if track.Tkhd == nil || track.Mdia.Mdhd == nil || track.Mdia.Mdhd.Timescale == 0 {
		return ErrUnsupported
	}
	info.VideoCodec = track.Mdia.Minf.Stbl.Stsd.Children[0].Type()
	info.Width = int(track.Tkhd.Width >> 16)
	info.Height = int(track.Tkhd.Height >> 16)
	info.DurationSeconds = float64(track.Mdia.Mdhd.Duration) / float64(track.Mdia.Mdhd.Timescale)
	return nil
}

func videoCodec(codec string) bool {
	switch codec {
	case "avc1", "avc3", "av01", "vp09":
		return true
	default:
		return false
	}
}
func audioCodec(codec string) bool { return codec == "mp4a" || codec == "Opus" }

// SaveIndex persists only generated bytes and immutable source IDs. No
// signed URL is written here. A new locator must independently establish the
// same source identity before this map can be rebound.
func (v *VirtualMP4) SaveIndex(path string) error {
	b, e := json.Marshal(v)
	if e != nil {
		return e
	}
	h := sha256.Sum256(b)
	envelope, e := json.Marshal(struct {
		Checksum string          `json:"checksum"`
		Data     json.RawMessage `json:"data"`
	}{hex.EncodeToString(h[:]), b})
	if e != nil {
		return e
	}
	return config.AtomicWrite(path, envelope, 0o600)
}

// LoadIndex verifies a saved index against freshly opened immutable source identities.
func LoadIndex(path string, sources map[string]Representation) (*VirtualMP4, error) {
	f, e := os.Open(path)
	if e != nil {
		return nil, e
	}
	defer f.Close()
	st, e := f.Stat()
	if e != nil || st.Size() > 256<<20 {
		return nil, ErrUnsupported
	}
	var envelope struct {
		Checksum string          `json:"checksum"`
		Data     json.RawMessage `json:"data"`
	}
	if json.NewDecoder(f).Decode(&envelope) != nil {
		return nil, ErrUnsupported
	}
	h := sha256.Sum256(envelope.Data)
	if hex.EncodeToString(h[:]) != envelope.Checksum {
		return nil, errors.New("packaging index checksum differs")
	}
	var v VirtualMP4
	if json.Unmarshal(envelope.Data, &v) != nil || v.Revision != PackagingVersion || len(v.Sources) != 2 || len(v.Header) < 16 || v.Length < int64(len(v.Header)) {
		return nil, ErrUnsupported
	}
	next := int64(len(v.Header))
	for i := range v.Spans {
		span := &v.Spans[i]
		s := sources[span.SourceID]
		if s == nil || s.ID() != span.SourceID || (span.SourceID != v.Sources[0] && span.SourceID != v.Sources[1]) || span.Output != next || span.Offset < 0 || span.Length <= 0 || span.Length > s.Size()-span.Offset || span.Length > v.Length-next {
			return nil, errors.New("index source revision differs")
		}
		span.source = s
		next += span.Length
		if next > v.Length {
			return nil, ErrUnsupported
		}
	}
	if next != v.Length {
		return nil, ErrUnsupported
	}
	v.setIdentity()
	return &v, nil
}
