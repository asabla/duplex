func TestMetadataArtifactsReuseBytesAndInvalidateExactInputs(t *testing.T) {
	a := &App{Measurements: &diagnostics.Recorder{}}
	ep := catalog.Episode{OwnerID: "owner", VideoID: "video", Title: "Original", Description: "Description", Season: 2026, Number: 1, FileNumber: 1, Updated: 10}

	first, err := a.episodeMetadata(ep)
	if err != nil {
		t.Fatal(err)
	}

	ep.Updated++

	again, err := a.episodeMetadata(ep)
	if err != nil || again.Media.ID() != first.Media.ID() || again.Modified != ep.Updated {
		t.Fatal("timestamp-only change regenerated bytes", err)
	}

	ep.Title = "Changed"

	changed, err := a.episodeMetadata(ep)
	if err != nil || changed.Media.ID() == first.Media.ID() {
		t.Fatal("metadata change reused old bytes", err)
	}

	ep.PlaylistID = "playlist"
	ep.OccurrenceID = "youtube-playlist:owner:playlist:video"
	ep.Number = 2

	reordered, err := a.episodeMetadata(ep)
	if err != nil || reordered.Media.ID() == changed.Media.ID() {
		t.Fatal("playlist order or identity reused old bytes", err)
	}

	names := map[int]string{1: "First"}

	show, err := a.showMetadataArtifact("owner", "Show", names, 10)
	if err != nil {
		t.Fatal(err)
	}

	same, err := a.showMetadataArtifact("owner", "Show", names, 11)
	if err != nil || same.Media.ID() != show.Media.ID() {
		t.Fatal("unchanged show regenerated bytes", err)
	}

	names[1] = "Second"

	updated, err := a.showMetadataArtifact("owner", "Show", names, 12)
	if err != nil || updated.Media.ID() == show.Media.ID() {
		t.Fatal("season-name change reused stale bytes", err)
	}

	data := make([]byte, show.Media.Size())
	if _, err = show.Media.ReadAt(t.Context(), data, 0); err != nil || !strings.Contains(string(data), "First") {
		t.Fatal("old handle bytes changed", err)
	}
}

func TestMetadataArtifactBudgetsAndEviction(t *testing.T) {
	a := &App{}
	for i := range metadataArtifactEntries + 20 {
		_, err := a.episodeMetadata(catalog.Episode{OwnerID: "owner", VideoID: fmt.Sprint(i), Season: 2026, Number: i + 1, FileNumber: i + 1})
		if err != nil {
			t.Fatal(err)
		}
	}

	if len(a.nfoCache.items) > metadataArtifactEntries || a.nfoCache.bytes > metadataArtifactBytes {
		t.Fatal("unbounded metadata cache")
	}

	for i := range 12 {
		_, err := a.episodeMetadata(catalog.Episode{OwnerID: "owner", VideoID: fmt.Sprint(i), Season: 2026, Number: i + 1, FileNumber: i + 1, Description: strings.Repeat("x", 1<<20)})
		if err != nil {
			t.Fatal(err)
		}
	}

	if a.nfoCache.bytes > metadataArtifactBytes {
		t.Fatal("metadata byte budget exceeded")
	}

	entry, err := library.EpisodeMetadata(library.Episode{ChannelID: "owner", VideoID: "oversize", Season: 2026, Number: 1, Description: strings.Repeat("x", int(metadataArtifactBytes))})
	if err != nil {
		t.Fatal(err)
	}

	a.nfoCache.put(metadataArtifact{key: "oversize", entry: entry})

	if _, ok := a.nfoCache.items["oversize"]; ok {
		t.Fatal("oversized artifact retained")
	}
}
